class MaxLeafNodes {
    // 지금까지 찾은 최대 리프 노드 수
    // 아무 것도 안 해도 리프는 최소 1개이므로 1로 시작
    int answer = 1;

    public int solution(int dist_limit, int split_limit) {

        // dfs 시작 상태
        //
        // c_dist = 1
        //   현재 확장 가능한 노드 수
        //   처음에는 루트 아래 시작 노드 1개가 있음
        //
        // u_dist = 1
        //   지금까지 사용한 분배 노드 수
        //   시작 노드 1개를 이미 사용 중인 상태로 보고 시작
        //
        // c_split = 1
        //   현재까지의 분배도
        //   아직 2나 3을 곱한 적이 없으므로 1
        //
        // leaf = 0
        //   지금까지 리프로 확정된 노드 수
        //   처음에는 아직 확정된 리프가 없음
        dfs(1, 1, 1, 0, dist_limit, split_limit);

        return answer;
    }

    public void dfs(long c_dist, long u_dist, long c_split, long leaf, int dist_limit, int split_limit) {

        // 방어 코드
        // 실제로는 c_dist가 음수가 되는 흐름은 거의 없음
        if(c_dist < 0) return;

        // -------------------------------------------------
        // 현재 상태에서 "여기서 멈추면" 리프가 몇 개인지 계산
        // -------------------------------------------------
        //
        // leaf   : 이미 리프로 확정된 개수
        // c_dist : 현재는 확장 가능하지만, 지금 멈추면 전부 리프가 되는 노드 수
        //
        // 따라서 현재 상태에서 멈췄을 때 최종 리프 수는
        // leaf + c_dist
        answer = (int)Math.max(answer, leaf + c_dist);

        // -------------------------------------------------
        // 현재 깊이의 자식 수를 2로 할지, 3으로 할지 선택
        // 문제 조건상 분배 노드는 자식이 2개 또는 3개만 가능
        // -------------------------------------------------
        for(int i=2;i<=3;i++) {

            // -------------------------------------------------
            // 이번 깊이에서 자식 수를 i로 정했을 때
            // 새로운 분배도는 c_split * i 가 된다
            //
            // 이 값이 split_limit를 넘으면
            // 이 깊이에서 i개 자식을 만드는 구조는 불가능
            // 따라서 이 분기는 더 탐색하지 않음
            // -------------------------------------------------
            if(c_split*i > split_limit) continue;

            // -------------------------------------------------
            // 현재 확장 가능한 노드가 c_dist개 있음
            // 이 노드들이 각각 자식 i개를 만들면
            // 다음 깊이에 생기는 노드 후보 수는 총 i * c_dist 개
            //
            // 하지만 이 모든 노드를 다음에도 계속 분배 노드로
            // 사용할 수 있는 건 아님
            //
            // dist_limit - u_dist
            //   앞으로 추가로 사용할 수 있는 분배 노드 수
            //
            // 따라서 다음 깊이에서 "계속 확장 가능한 노드"로
            // 남길 수 있는 최대 개수는
            // min(i * c_dist, dist_limit - u_dist)
            //
            // 이 값을 maxJ라고 둠
            // -------------------------------------------------
            long maxJ = Math.min(i*c_dist, dist_limit-u_dist);

            // -------------------------------------------------
            // 다음 dfs 상태로 넘어감
            //
            // 1) c_dist -> maxJ
            //    다음 깊이에서 계속 확장 가능한 노드 수
            //
            // 2) u_dist -> u_dist + maxJ
            //    이번에 다음 깊이 노드 중 maxJ개를 분배 노드로 사용하므로
            //    사용량이 그만큼 늘어남
            //
            // 3) c_split -> c_split * i
            //    이번 깊이에서 자식 수 i를 선택했으므로
            //    분배도에 i를 곱해 갱신
            //
            // 4) leaf -> leaf + (i*c_dist - maxJ)
            //    이번에 새로 생긴 노드 총 수는 i*c_dist
            //    그중 maxJ개는 다음에도 계속 확장할 노드
            //    나머지 (i*c_dist - maxJ)개는 더 이상 확장하지 못하므로
            //    이번에 리프로 확정되는 노드 수
            // -------------------------------------------------
            dfs(
                maxJ,                      // 다음 깊이에서 확장 가능한 노드 수
                u_dist + maxJ,            // 지금까지 사용한 분배 노드 수
                c_split * i,              // 갱신된 분배도
                leaf + (i*c_dist - maxJ), // 새로 리프로 확정된 노드 반영
                dist_limit,
                split_limit
            );
        }
    }
}